public class Oper_comparacion {
    static void main(String[] args) {
        int valor = 90, valor2 = 50;

        //igualdad
        System.out.println(valor==valor2); //comparacion su es igual

        //distinto a..
        System.out.println(valor!=valor2);

        //mayor que
        System.out.println(valor > valor2 );

        //menor que
        System.out.println(valor < valor2 );

        //menor o igual que..
        System.out.println(valor <= valor2 );

        //mayor o igual que..
        System.out.println(valor >= valor2 );




    }
}
