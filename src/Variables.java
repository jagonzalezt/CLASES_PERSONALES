/*
¿QUE SON LAS VARIABLES?
* SON LO MAS IMPORTANTE DE UN LENGUAJE, SON LAS ENTIDADES, CONTIENEN VALORES O DATOS
* UNA DECLARACION DE VARIABLE SIEMPRE CONTIENE DOS PARTES, EL TIPO DE DATO DE LA VARIABLE Y SU NOMBRE
*/
/*
TIPO DE DATO:
* EL TIPO DE VARIABLE DETERMINA EL VALOR QUE LA VARIABLE PUEDE CONTENER Y LAS OPERACIONES QUE
SE PUEDEN REALIZAR CON ELLAS: tipo texto, Numerico, Booleano, Double
*/
public class Variables {
    static void main(String[] args) {
        String Nombre = "Informaticonfig";  // Tipo de dato texto
        int valor = 100;    // tipo de dato Enteto
        double valor2 = 10.1;   // tipo de dato para decimales
        char letra = 'A';    // tipo de dato de caracter
        boolean esEstudiante = false;

        System.out.println(Nombre);
        System.out.println(valor);
        System.out.println(valor2);
        System.out.println(letra);
        System.out.println(esEstudiante);
    }
}
